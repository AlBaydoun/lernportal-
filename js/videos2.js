function hasVids(k){ const v=VIDEOS[k]; return !!v && ((v.de||[]).length || (v.ru||[]).length); }
/* follows the alias chain (with loop guard) so every lesson resolves to a video */
function videosForLesson(key){
  if(hasVids(key)) return {key, v:VIDEOS[key], alias:false};
  let cur = VIDEO_ALIAS[key], hops = 0;
  const seen = new Set([key]);
  while(cur && !seen.has(cur) && hops++ < 6){
    if(hasVids(cur)) return {key:cur, v:VIDEOS[cur], alias:true};
    seen.add(cur);
    cur = VIDEO_ALIAS[cur];
  }
  return null;
}
